static void drawLevel4() {
    for (int row = 0; row < MAP_ROWS; ++row) {
        for (int col = 0; col < MAP_COLS; ++col) {
            int tile = LEVEL4_MAP[row][col];
            if (tile == 0) continue;
            int x = col * TILE_SIZE;
            int y = row * TILE_SIZE;
            if (tile == 1)      drawDirtBlock(x, y, TILE_SIZE);
            else if (tile == 2) drawGrassBlock(x, y, TILE_SIZE);
            else if (tile == 3) drawSpikeBlock(x, y, TILE_SIZE);
            else if (tile == 4) drawLavaBlock(x, y, TILE_SIZE);
        }
    }
}

