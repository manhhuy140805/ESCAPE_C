static void drawLevel3SandstoneBlock(int x, int y, int size) {
    drawRect(x, y, size, size, 0xC8843D);
    drawRect(x + 2, y + 2, size - 4, size / 4, 0xE8AC55);
    drawRect(x + 2, y + size - 5, size - 4, 3, 0x985026);
    setcolor(HEX2COLOR(0xA9602B));
    line(x + size / 3, y + size / 2, x + size - 3, y + size / 2);
}

static void drawLevel3OasisBlock(int x, int y, int size) {
    drawLevel3SandstoneBlock(x, y, size);
    drawRect(x, y, size, size / 5, 0x36A98A);
    drawRect(x + 3, y + size / 5, size - 6, 2, 0xF4D06F);
}

static void drawLevel3ThornBlock(int x, int y, int size) {
    int thornColor = COLOR(239, 214, 154);
    setcolor(thornColor);
    setfillstyle(SOLID_FILL, thornColor);
    int points[8] = {x, y + size, x + size / 2, y + 4, x + size, y + size, x, y + size};
    fillpoly(4, points);
}

static void drawLevel3QuicksandBlock(int x, int y, int size) {
    drawRect(x, y, size, size, 0xD67B32);
    drawRect(x, y, size, size / 3, 0xF2BB55);
    drawRect(x + 3, y + size / 2, size - 6, 3, 0xB95B2C);
}

static void drawLevel3() {
    for (int row = 0; row < MAP_ROWS; ++row) {
        for (int col = 0; col < MAP_COLS; ++col) {
            int tile = LEVEL3_MAP[row][col];
            if (tile == 0) continue;

            int x = col * TILE_SIZE;
            int y = row * TILE_SIZE;

            if (tile == 1) {
                if (row == 0 || row == MAP_ROWS - 1 || col == 0 || col == MAP_COLS - 1) {
                    drawBrickBlock(x, y, TILE_SIZE);
                } else {
                    drawLevel3SandstoneBlock(x, y, TILE_SIZE);
                }
            } else if (tile == 2) {
                drawLevel3OasisBlock(x, y, TILE_SIZE);
            } else if (tile == 3) {
                drawLevel3ThornBlock(x, y, TILE_SIZE);
            } else if (tile == 4) {
                drawLevel3QuicksandBlock(x, y, TILE_SIZE);
            }
        }
    }
}

